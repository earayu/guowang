# ------------------------------------------------------------ 抽取 V5 真跑规则原文
def build_rules():
    d = json.load(io.open(BASE + 'sgcc_l1_results.json', encoding='utf-8'))
    rec = next(r for r in d['results'] if r['name'].startswith('V5'))
    a = rec['answer']
    s = a.find('# 第一部分')
    e = a.find('# 第二部分')
    assert s > 0 and e > s, 'V5 否决情形表区块定位失败'
    seg = a[s:e]
    rules = []
    for line in seg.split('\n'):
        if not line.startswith('|'):
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) != 3 or not cells[0].isdigit():
            continue
        no, cat, text = cells
        parts = re.split(r'／', cat, maxsplit=1)
        category = parts[0].strip()
        subcat = parts[1].strip() if len(parts) > 1 else ''
        rules.append({
            'rule_id': 'GW-HB-FJ-%03d' % int(no),
            'row': int(no),
            'category': category,
            'subcategory': subcat,
            'rule_text': text,
            'chapter': '第三章 评标办法 → 评标办法前附表之二：初步评审标准 → 否决情形表',
            'batch': '152507 / 1525K1',
            'packages': '18 个标包采购文件（同表同文；第 46 行按版本不同）',
            'representative_docs': [
                'S2507_4003导线震动在线监测装置__…（152507）.docx（第 13 节）',
                'S1K1_4032视频在线监测装置__…（1525K1）-资格预审.docx（第 13 节）',
                'S1K1_4032视频在线监测装置__…（1525K1）-资格后审.docx（第 13 节）',
            ],
            'source': 'sgcc_l1_results.json → V5 答案（turn %s）逐条回读原文' % rec.get('turn_id', ''),
            'evidence_level': '【T】AI 逐条回读的条款原文摘录；**尚未经业务方对照原文核对**',
            'status': 'CANDIDATE',
            'ai_can': '检索命中该行、回读原文、列为候选待核项、给出条款位置',
            'ai_cannot': '自动否决投标、判定是否违规、赋分、定标、代评标委员会签署',
            'confirm_role': '评标委员会（依招标文件）／招标人（澄清与修改）',
            'version_diff': int(no) == 46,
        })
    assert len(rules) == 46, '期望 46 行，实得 %d' % len(rules)
    return rules, rec

RULES, V5REC = build_rules()

