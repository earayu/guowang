def patch(path, pairs):
    s = io.open(B + path, encoding='utf-8').read()
    for old, new in pairs:
        n = s.count(old)
        assert n == 1, '%s count=%d for %r' % (path, n, old[:80])
        s = s.replace(old, new, 1)
    io.open(B + path, 'w', encoding='utf-8').write(s)
    print('OK patch', path, len(pairs), 'edits')


def patch_soft(path, pairs):
    """幂等：已应用的替换直接跳过，用于可重复运行的装配脚本改造。"""
    s = io.open(B + path, encoding='utf-8').read()
    n_applied = 0
    for old, new in pairs:
        n = s.count(old)
        if n == 0:
            continue
        assert n == 1, '%s count=%d for %r' % (path, n, old[:80])
        s = s.replace(old, new, 1)
        n_applied += 1
    io.open(B + path, 'w', encoding='utf-8').write(s)
    print('OK patch_soft', path, n_applied, '/', len(pairs), 'edits applied')


